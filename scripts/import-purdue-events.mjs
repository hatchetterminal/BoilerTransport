import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const sports = [
  ['football', 'Football', 'Ross-Ade Stadium'],
  ['mens-basketball', 'Men’s basketball', 'Mackey Arena'],
  ['womens-basketball', 'Women’s basketball', 'Mackey Arena'],
  ['volleyball', 'Volleyball', null],
  ['womens-soccer', 'Soccer', null],
];

const plainText = (text) =>
  text
    .replace(/<[^>]*>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&nbsp;/g, ' ')
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&quot;/g, '"')
    .replace(/&#x([a-f\d]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .trim();

// The visible schedule controls time/status. JSON-LD contains arbitrary timestamps for TBA games.
export function parseSchedule(html, { slug, label, defaultVenue }) {
  const graph = JSON.parse(
    html.match(/<script[^>]*type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/)?.[1] || '{}',
  )['@graph'];
  if (!Array.isArray(graph)) throw new Error(`${slug}: missing schedule data`);
  const entries = graph.filter((item) => item['@type'] === 'Event');
  const blocks = html.split(/<div class="schedule-event-item(?: [^"]*)?"[^>]*>/).slice(1);
  if (!entries.length || entries.length !== blocks.length)
    throw new Error(`${slug}: schedule format changed; snapshot not replaced`);
  const events = [];
  entries.forEach((entry, index) => {
    const block = blocks[index];
    const field = (name) =>
      plainText(
        block.match(new RegExp(`class="${name}"[^>]*>([\\s\\S]*?)</(?:strong|span|div)>`))?.[1] ||
          '',
      );
    const location = field('schedule-event-location');
    // A neutral-site "vs." game is not a West Lafayette home game.
    if (!location.startsWith('West Lafayette') || !entry.name.startsWith('Purdue vs. ')) return;
    const opponent = field('schedule-default-event__title');
    if (!opponent || entry.name !== `Purdue vs. ${opponent}`)
      throw new Error(`${slug}: opponent mismatch`);
    const date = entry.eventSchedule?.startDate;
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) throw new Error(`${slug}: missing game date`);
    const timeLabel = field('schedule-event-item-result__label');
    const time = timeLabel.match(/^(\d{1,2}):(\d{2}) (AM|PM) (EDT|EST)$/);
    let startTime = null;
    if (time) {
      const hour = (Number(time[1]) % 12) + (time[3] === 'PM' ? 12 : 0);
      startTime = new Date(
        `${date}T${String(hour).padStart(2, '0')}:${time[2]}:00${time[4] === 'EDT' ? '-04:00' : '-05:00'}`,
      ).toISOString();
    }
    const status = /^[WLT]$/.test(timeLabel)
      ? 'completed'
      : /cancel|postpon/i.test(timeLabel)
        ? 'cancelled'
        : 'scheduled';
    const venue = location.split(' / ')[1] || defaultVenue || location;
    events.push({
      id: `${slug}-${date}-${opponent.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
      title: entry.name,
      opponent,
      sport: slug,
      sport_label: label,
      event_type: slug.includes('basketball') ? 'basketball' : slug,
      date,
      start_time: startTime,
      time_note: time ? null : timeLabel === 'TBA' ? 'Time TBA' : timeLabel,
      venue,
      is_home: true,
      status,
      source_url: `https://purduesports.com/sports/${slug === 'womens-soccer' ? 'soccer' : slug}/schedule`,
    });
  });
  return { events, schedule_title: graph.find((item) => item['@type'] === 'WebPage')?.name };
}

async function main() {
  const directory = process.argv[2];
  const verifiedOn = new Date().toISOString().slice(0, 10);
  const results = await Promise.all(
    sports.map(async ([slug, label, defaultVenue]) => {
      const url = `https://purduesports.com/sports/${slug === 'womens-soccer' ? 'soccer' : slug}/schedule`;
      let html;
      if (directory) html = await readFile(`${directory}/${slug}.html`, 'utf8');
      else {
        const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
        if (!response.ok) throw new Error(`${url}: ${response.status}`);
        html = await response.text();
      }
      return { slug, label, url, ...parseSchedule(html, { slug, label, defaultVenue }) };
    }),
  );
  const snapshot = {
    verified_on: verifiedOn,
    timezone: 'America/Indiana/Indianapolis',
    schedules: results.map(({ events, ...source }) => ({ ...source, home_count: events.length })),
    events: results
      .flatMap((result) => result.events)
      .sort(
        (a, b) =>
          a.date.localeCompare(b.date) || (a.start_time || 'z').localeCompare(b.start_time || 'z'),
      ),
  };
  // All sources must parse successfully before the existing offline snapshot is replaced.
  await writeFile(
    new URL('../src/data/purdueEventsSource.js', import.meta.url),
    `// Generated by scripts/import-purdue-events.mjs. Do not invent times for TBA games.\nexport default ${JSON.stringify(snapshot, null, 2)};\n`,
  );
  console.log(`Saved ${snapshot.events.length} Purdue home games; checked ${verifiedOn}.`);
  results.forEach((result) =>
    console.log(`${result.label}: ${result.events.length} home games (${result.schedule_title})`),
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
