import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const service = 'https://services1.arcgis.com/mLNdQKiKsj5Z5YMN/arcgis/rest/services';
const sourceDirIndex = process.argv.indexOf('--source-dir');
const sourceDir = sourceDirIndex < 0 ? null : process.argv[sourceDirIndex + 1];
const mapUrl =
  'https://purdueuniversity.maps.arcgis.com/apps/instant/basic/index.html?appid=47529701e46e48a08289fc46cb6de802';

async function getJson(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  const data = await response.json();
  if (data.error) throw new Error(JSON.stringify(data.error));
  return data;
}

async function loadLayer(name) {
  if (sourceDir)
    return JSON.parse(await fs.readFile(path.join(sourceDir, `purdue-${name}.geojson`), 'utf8'));
  const url = `${service}/${name}/FeatureServer/0/query`;
  const count = await getJson(`${url}?where=1%3D1&returnCountOnly=true&f=json`);
  const data = await getJson(`${url}?where=1%3D1&outFields=*&outSR=4326&f=geojson`);
  if (data.exceededTransferLimit || data.features?.length !== count.count)
    throw new Error(`Incomplete ${name} download`);
  return data;
}

const [parking, buildings, metadata] = await Promise.all([
  loadLayer('SurfaceParkingLots'),
  loadLayer('BuildingShapesZip4'),
  sourceDir
    ? fs
        .readFile(path.join(sourceDir, 'purdue-SurfaceParkingLots-meta.json'), 'utf8')
        .then(JSON.parse)
    : getJson(`${service}/SurfaceParkingLots/FeatureServer/0?f=json`),
]);
const fields = [
  'FID',
  'LOT_NUMB',
  'LotMapShee',
  'LOT_PERM',
  'LotName',
  'LotDesc',
  'PTYPE',
  'Owner',
  'Control',
  'NotALot',
];
const knownPermits = new Set([
  'A',
  'AB',
  'ABC',
  'R',
  'RG',
  'FSCL',
  'M',
  'GGPP',
  'SP',
  'RE',
  'VAL',
  'CONT',
  'UV',
  'NPR',
  'SCG',
]);
const roundCoordinates = (value) =>
  Array.isArray(value) ? value.map(roundCoordinates) : Number(value.toFixed(7));
const features = parking.features.map((feature) => {
  if (!knownPermits.has(feature.properties.LOT_PERM))
    throw new Error(`Review new permit code: ${feature.properties.LOT_PERM}`);
  if (!['Polygon', 'MultiPolygon'].includes(feature.geometry?.type))
    throw new Error(`Review geometry: ${feature.id}`);
  return {
    id: feature.id,
    properties: Object.fromEntries(
      fields.map((key) => [
        key,
        typeof feature.properties[key] === 'string'
          ? feature.properties[key].trim()
          : feature.properties[key],
      ]),
    ),
    geometry: {
      type: feature.geometry.type,
      coordinates: roundCoordinates(feature.geometry.coordinates),
    },
  };
});
const text = features.map((f) => `${f.properties.LotName} ${f.properties.LotDesc}`).join(' ');
const buildingNames = Object.fromEntries(
  buildings.features
    .filter(
      (f) =>
        f.properties.BLDG_ABBR && f.properties.BUILDING_N && text.includes(f.properties.BLDG_ABBR),
    )
    .map((f) => [f.properties.BLDG_ABBR, f.properties.BUILDING_N]),
);
const garageBuildings = buildings.features
  .filter((f) => /Parking Garage/.test(f.properties.BUILDING_N || ''))
  .map((f) => ({
    code: f.properties.BLDG_ABBR,
    name: f.properties.BUILDING_N,
    address: f.properties.ADDRESS,
  }));
const output = {
  source_url: mapUrl,
  service_url: `${service}/SurfaceParkingLots/FeatureServer/0`,
  source_updated: new Date(metadata.editingInfo.dataLastEditDate).toISOString().slice(0, 10),
  retrieved_on: new Date().toISOString().slice(0, 10),
  source_record_count: features.length,
  building_names: buildingNames,
  garage_buildings: garageBuildings,
  features,
};
// One feature per line keeps a future inventory refresh reviewable.
const { features: rows, ...header } = output;
await fs.writeFile(
  path.join(root, 'src/data/purdueParkingSource.js'),
  `// Generated by scripts/import-purdue-parking.mjs.\nexport default ${JSON.stringify(header, null, 2).slice(0, -2)},\n  "features": [\n${rows.map((row) => `    ${JSON.stringify(row)}`).join(',\n')}\n  ]\n};\n`,
);
console.log(
  `Saved ${features.length} source records, updated ${output.source_updated}. Review policies and run parking data tests before publishing.`,
);
